$ErrorActionPreference = 'Stop'

# Preserve historical patch notes while moving them out of the repository root.
$historyDirectory = Join-Path $PSScriptRoot 'docs\change-history'
New-Item -ItemType Directory -Force -Path $historyDirectory | Out-Null

$historicalNotes = @(
    'ABOUT_FUTURE_FILM_VISION_UPDATE.md',
    'APPLY_README.md',
    'APPS_INVESTORS_UPDATE.md',
    'BUILD_FIX_README.md',
    'LINKEDIN_CONTACT_UPDATE.md',
    'MOBILE_HEADER_NAVIGATION_UPDATE.md',
    'MUSIC_BOOK_SOCIAL_UPDATE.md',
    'PROJECT_AND_INVESTOR_ENQUIRIES_UPDATE.md',
    'ROUTE_SCROLL_RESET_README.md',
    'SEO_IDENTITY_UPDATE_README.md',
    'TELEGRAM_AND_CREATIVE_IDENTITY_UPDATE.md',
    'WIZZYLUX_BRAND_SPELLING_UPDATE.md'
)

foreach ($file in $historicalNotes) {
    $source = Join-Path $PSScriptRoot $file
    $destination = Join-Path $historyDirectory $file
    if (Test-Path -LiteralPath $source) {
        if (Test-Path -LiteralPath $destination) {
            throw "Both root and history copies exist for $file. Compare them manually before continuing."
        }
        Move-Item -LiteralPath $source -Destination $destination
        Write-Host "Archived $file"
    }
}

# tsbuildinfo is generated by TypeScript and is now ignored by .gitignore.
$cacheFile = Join-Path $PSScriptRoot 'tsconfig.tsbuildinfo'
if (Test-Path -LiteralPath $cacheFile) {
    git -C $PSScriptRoot rm -- tsconfig.tsbuildinfo
    if ($LASTEXITCODE -ne 0) {
        throw 'Could not remove the tracked TypeScript build cache from Git.'
    }
}

Write-Host 'Repository hygiene cleanup complete. Review git status before committing.' -ForegroundColor Green
